/* Refresh + input-poll cadence. Default is 33ms (30fps) -> up to ~66ms from a
 * wheel detent to the highlight moving. Measured scroll cost is ~1.2% of one core,
 * so there's ample headroom to poll+repaint at ~60fps; 16ms roughly halves the
 * worst-case input-to-paint latency. Panel transport ceiling is ~65-130fps, so the
 * wire keeps up. This is the real responsiveness lever (render mode was a wash).
 * 14ms (71.4 Hz) tracks the panel's programmed ~70 Hz (E8h=11 00; no TE line, so
 * unverifiable): at 16ms (62.5 fps) every ~8th panel refresh repeated a frame.
 * Artists scroll 59->66 fps, same drops, UI CPU +2.4 pts (2026-10-05 A/B). */
#define LV_DEF_REFR_PERIOD 14
#define LV_USE_STDLIB_MALLOC LV_STDLIB_BUILTIN
#define LV_MEM_SIZE (384 * 1024)            /* heap; 320x240x2 buffers come from DRM */
